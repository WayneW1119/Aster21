"""Build the self-contained browser entry without Node or runtime CDN requests."""
from pathlib import Path

WEB = Path(__file__).resolve().parents[1] / 'relay/web'
SOURCES = ('markdown-it.min.js', 'markdown.js', 'image-previews.js', 'app-main.js')
HEADER = '// Generated by tools/build_web.py; edit the listed web sources, then rebuild.\n'


def bundle():
    return HEADER + '\n;\n'.join((WEB / name).read_text(encoding="utf-8") for name in SOURCES)


if __name__ == '__main__':
    (WEB / 'app.js').write_text(bundle(), encoding="utf-8", newline="\n")
